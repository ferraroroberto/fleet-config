"""Regenerate the per-repo section of ``docs/fleet-guide.md`` from ``fleet.data.js``.

The guide is hand-written prose except for one block, the list of fleet repos by
layer, which sits between two marker comments and is rewritten from the same
single source the map renderers read: each repo's ``.fleet.toml``, aggregated by
``build_data.py``. Everything outside the markers is left byte-for-byte alone, so
the prose can be edited freely and the repo list can never be hand-copied stale.

Usage::

    E:/automation/fleet-config/.venv/Scripts/python.exe .claude/skills/system-map/render_guide.py          # rewrite the block
    E:/automation/fleet-config/.venv/Scripts/python.exe .claude/skills/system-map/render_guide.py --check  # exit 1 if stale
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "skills" / "_lib"))
from fleet_core.check_or_write import check_or_write  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from render_mermaid import DATA_JS, SECTIONS, load_data  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[3]
GUIDE = REPO_ROOT / "docs" / "fleet-guide.md"

START = "<!-- fleet-repos:start (generated by .claude/skills/system-map/render_guide.py; do not hand-edit) -->"
END = "<!-- fleet-repos:end -->"

# Section key in fleet.data.js -> (heading, the `layer` value a repo writes in its .fleet.toml).
LAYERS = {
    "governance": ("Governance", "governance"),
    "enabling": ("Enabling", "enabling"),
    "web": ("Working apps: web", "working-web"),
    "pipe": ("Working apps: pipelines", "working-pipe"),
}

_BOLD_RE = re.compile(r"</?b>")
_TAG_RE = re.compile(r"<[^>]+>")


def plain(description: str) -> str:
    """A card description (written as innerHTML) as plain Markdown table text."""
    text = _TAG_RE.sub("", _BOLD_RE.sub("**", description))
    return html.unescape(text).replace("|", "\\|").strip()


def _port(card: dict) -> str:
    port = card.get("port")
    if port in (None, ""):
        return "—"
    text = str(port)
    return text if text.startswith(":") else f":{text}"


def render_block(data: dict) -> str:
    """The generated block, markers included — a pure function of ``data``."""
    lines = [START, ""]
    for section in SECTIONS:
        heading, layer = LAYERS[section]
        cards = data.get(section, [])
        lines += [f"### {heading} (`layer = \"{layer}\"`, {len(cards)} repos)", "",
                  "| | Repo | What it is | Port |", "|---|---|---|---|"]
        for card in cards:
            repo = card.get("repo", card["nm"])
            lines.append(f"| {card['ic']} | `{repo}` | {plain(card['ds'])} | {_port(card)} |")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def splice(guide_text: str, block: str) -> str:
    """Replace the marked block in ``guide_text``; a guide without both markers is an error."""
    start, end = guide_text.find(START), guide_text.find(END)
    if start < 0 or end < start:
        raise ValueError(f"{GUIDE.name}: the fleet-repos start/end markers are missing or out of order")
    return guide_text[:start] + block + guide_text[end + len(END):]


def regenerate(data_path: Path = DATA_JS, guide_path: Path = GUIDE) -> str:
    """The full guide text with its block rewritten from ``data_path``."""
    data = load_data(data_path.read_text(encoding="utf-8"))
    return splice(guide_path.read_text(encoding="utf-8"), render_block(data))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Regenerate the repo list in docs/fleet-guide.md.")
    ap.add_argument("--check", action="store_true", help="exit 1 if the repo list is stale")
    args = ap.parse_args(argv)

    return check_or_write(GUIDE, regenerate(), "render_guide",
                          Path(__file__),
                          args.check, current=GUIDE.read_text(encoding="utf-8"), newline="\n")


if __name__ == "__main__":
    sys.exit(main())
