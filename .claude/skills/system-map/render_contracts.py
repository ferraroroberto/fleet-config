"""Render the contracts declared in ``architecture/fleet.data.js`` as one page.

``architecture/CONTRACTS.md`` lists every interface a fleet repo declares (with
a link to its canonical doc), what each repo owns and does not own, and its
declared dependencies. Same single source as the two map renderers: each
repo's ``.fleet.toml`` keys, aggregated by ``build_data.py``. Repos that
declare none of the keys are left out, so the page shows what is declared, and
``build_data.py --coupling`` shows what is used without being declared.

Usage::

    E:/automation/fleet-config/.venv/Scripts/python.exe .claude/skills/system-map/render_contracts.py          # regenerate CONTRACTS.md
    E:/automation/fleet-config/.venv/Scripts/python.exe .claude/skills/system-map/render_contracts.py --check  # exit 1 if stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "skills" / "_lib"))
from gh_issue_fetch import OWNER  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from render_mermaid import DATA_JS, SECTIONS, load_data  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[3]
CONTRACTS_OUT = REPO_ROOT / "architecture" / "CONTRACTS.md"

HEADER = """\
<!-- GENERATED by .claude/skills/system-map/render_contracts.py from architecture/fleet.data.js. DO NOT hand-edit: change the repo's .fleet.toml (schema: architecture/README.md), then regenerate. -->
# Fleet contracts

What each fleet repo declares it exposes, owns and depends on. A repo with no declaration is not listed.
"""


def _repo(card: dict) -> str:
    return card.get("repo", card["nm"])


def _cell(items: list) -> str:
    return ", ".join(items) if items else "—"


def render(data: dict) -> str:
    """The full committed ``CONTRACTS.md`` text — pure function of ``data``."""
    cards = [c for s in SECTIONS for c in data.get(s, [])
             if any(k in c for k in ("ifs", "owns", "not_owns", "deps"))]
    lines = [HEADER, "## Interfaces", "", "| Repo | Interface | Kind | Doc |", "|---|---|---|---|"]
    for card in cards:
        for i in card.get("ifs", []):
            url = f"https://github.com/{OWNER}/{_repo(card)}/blob/main/{i['doc']}"
            lines.append(f"| {_repo(card)} | {i['name']} | {i['kind']} | [{i['doc']}]({url}) |")
    lines += ["", "## Ownership", "", "| Repo | Owns | Does not own |", "|---|---|---|"]
    for card in cards:
        if "owns" in card or "not_owns" in card:
            lines.append(f"| {_repo(card)} | {_cell(card.get('owns', []))} | {_cell(card.get('not_owns', []))} |")
    lines += ["", "## Dependencies", "", "| Repo | Depends on |", "|---|---|"]
    for card in cards:
        if "deps" in card:
            deps = [d["repo"] + (f" ({d['interface']})" if "interface" in d else "") for d in card["deps"]]
            lines.append(f"| {_repo(card)} | {_cell(deps)} |")
    return "\n".join(lines) + "\n"


def regenerate(data_path: Path = DATA_JS) -> str:
    return render(load_data(data_path.read_text(encoding="utf-8")))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Render the declared fleet contracts as CONTRACTS.md.")
    ap.add_argument("--check", action="store_true", help="exit 1 if CONTRACTS.md is stale")
    args = ap.parse_args(argv)

    rendered = regenerate()
    current = CONTRACTS_OUT.read_text(encoding="utf-8") if CONTRACTS_OUT.exists() else None
    if args.check:
        if rendered != current:
            print("render_contracts: STALE — run "
                  "`E:/automation/fleet-config/.venv/Scripts/python.exe .claude/skills/system-map/render_contracts.py` "
                  "and commit.", file=sys.stderr)
            return 1
        print("render_contracts: up to date.")
        return 0
    if rendered != current:
        CONTRACTS_OUT.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"render_contracts: regenerated {CONTRACTS_OUT.name}.")
    else:
        print(f"render_contracts: {CONTRACTS_OUT.name} already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
